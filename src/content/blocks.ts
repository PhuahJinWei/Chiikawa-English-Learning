/** Normalises written English to a dictionary key: lower case, no ? ! . , or extra spaces. */
export function keyOf(text: string): string {
  return text
    .toLowerCase()
    .replace(/[?!.,]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

