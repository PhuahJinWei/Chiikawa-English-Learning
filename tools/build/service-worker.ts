/// <reference types="node" />
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, resolve, sep } from 'node:path';
import type { Plugin } from 'vite';

/**
 * Writes dist/sw.js and dist/precache.json after a production build. The service worker keeps every file of the
 * app on the phone, so it opens without a connection.
 *
 * Versions come from the content (REVIEW 5.4): each file has a hash, and the version is a hash of those, so a build
 * that changes nothing is not a new version. When a new version installs, files whose hash did not change are copied
 * from the old version's cache instead of being downloaded again. precache.json is not kept offline, so the
 * self-check can compare the running version with the newest one online.
 */
const SKIP = [
  /^sw\.js$/,
  /^precache\.json$/,
  /\.map$/,
  // three's DRACOLoader names its decoder files statically, so the build copies them, but the stage loads its own
  // decoder from draco/ (see src/stage). These copies are never requested.
  /^assets\/draco_/,
];

function walk(dir: string, root = dir): string[] {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) return walk(full, root);
    return [relative(root, full).split(sep).join('/')];
  });
}

const SW = String.raw`// Generated by tools/build/service-worker.ts. Do not edit.
const VERSION = '__VERSION__';
// Every file with a hash of its content. './' is the page itself (index.html) as the phone asks for it.
const FILES = __FILES__;
const CACHE = 'eigo-friends-' + VERSION;
// Each version keeps its own file list in its cache, so the next version can tell which files did not change.
const LIST = '__files.json';

async function previous() {
  for (const key of await caches.keys()) {
    if (!key.startsWith('eigo-friends-') || key === CACHE) continue;
    const cache = await caches.open(key);
    const list = await cache.match(LIST);
    if (!list) continue;
    try {
      return { cache, files: await list.json() };
    } catch (e) {
      // unreadable: download everything
    }
  }
  return null;
}

// Downloads one file, fresh (not from the browser's HTTP cache), and checks it is the version this worker expects:
// right after a deploy the server can still hand out an old copy, and a wrong file kept here would stay until that
// file changes again.
async function download(path) {
  const res = await fetch(new Request(path, { cache: 'reload' }));
  if (!res.ok) throw new Error(path + ': HTTP ' + res.status);
  const digest = new Uint8Array(await crypto.subtle.digest('SHA-256', await res.clone().arrayBuffer()));
  let hex = '';
  for (const b of digest) hex += (b < 16 ? '0' : '') + b.toString(16);
  if (hex.slice(0, 16) !== FILES[path]) throw new Error(path + ': not the expected version yet');
  return res;
}

self.addEventListener('install', (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      const old = await previous();
      const todo = [];
      for (const path of Object.keys(FILES)) {
        const same = old && old.files[path] === FILES[path];
        const hit = same ? await old.cache.match(path, { ignoreVary: true }) : undefined;
        if (hit) await cache.put(path, hit);
        else todo.push(path);
      }
      // A few at a time. Any file that fails, or is not the expected version, fails the whole install: it is tried
      // again at the next check, and the version on the phone keeps working meanwhile.
      let next = 0;
      const one = async () => {
        while (next < todo.length) {
          const path = todo[next++];
          await cache.put(path, await download(path));
        }
      };
      await Promise.all([one(), one(), one(), one(), one(), one()]);
      // Written last: only a complete copy has a list, so only a complete copy is ever reused.
      await cache.put(LIST, new Response(JSON.stringify(FILES), { headers: { 'Content-Type': 'application/json' } }));
    })(),
  );
  // No skipWaiting here: the app tells a new version to take over only on its home screen, never mid-lesson.
});

self.addEventListener('message', (event) => {
  const msg = event.data || {};
  if (msg.type === 'activate') self.skipWaiting();
  // The self-check and the Today screen ask whether everything is kept offline.
  if (msg.type === 'status' && event.ports && event.ports[0]) {
    event.waitUntil(
      (async () => {
        const cache = await caches.open(CACHE);
        let cached = 0;
        for (const path of Object.keys(FILES)) if (await cache.match(path, { ignoreVary: true })) cached++;
        event.ports[0].postMessage({ version: VERSION, files: Object.keys(FILES).length, cached });
      })(),
    );
  }
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) {
        if (key.startsWith('eigo-friends-') && key !== CACHE) await caches.delete(key);
      }
      await self.clients.claim();
    })(),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      // ignoreVary: hosts send "Vary: Origin", and the browser's module-script requests carry an Origin header the
      // install requests did not, so a strict match would miss the app's own files when offline.
      const hit = await cache.match(req, { ignoreSearch: true, ignoreVary: true });
      if (hit) return hit;
      if (req.mode === 'navigate') {
        const index = await cache.match('./', { ignoreVary: true });
        if (index) return index;
      }
      try {
        return await fetch(req);
      } catch (e) {
        return new Response('', { status: 504, statusText: 'offline' });
      }
    })(),
  );
});
`;

/** The first 16 hex digits of a file's SHA-256: what sw.js checks downloads against. */
export const hashOf = (data: string | Buffer) => createHash('sha256').update(data).digest('hex').slice(0, 16);

/** The service worker for one version (exported for tests/service-worker.test.ts). A function as the replacement,
 * so nothing in the list is read as a replacement pattern. */
export const swSource = (version: string, files: Record<string, string>): string =>
  SW.replace('__VERSION__', () => version).replace('__FILES__', () => JSON.stringify(files));

export function serviceWorker(): Plugin {
  let outDir = 'dist';
  return {
    name: 'eigo-friends-service-worker',
    apply: 'build',
    configResolved(config) {
      outDir = resolve(config.root, config.build.outDir);
    },
    closeBundle() {
      const paths = walk(outDir)
        .filter((f) => !SKIP.some((re) => re.test(f)))
        .sort();
      const files: Record<string, string> = {};
      for (const f of paths) files[f] = hashOf(readFileSync(join(outDir, f)));
      files['./'] = files['index.html'];
      const version = hashOf(JSON.stringify(Object.entries(files).sort())).slice(0, 12);
      writeFileSync(join(outDir, 'precache.json'), JSON.stringify({ version, files }));
      writeFileSync(join(outDir, 'sw.js'), swSource(version, files));
      const kb = paths.reduce((t, f) => t + statSync(join(outDir, f)).size, 0) / 1024;
      console.log(`service worker ${version}: ${paths.length + 1} files, ${(kb / 1024).toFixed(2)} MB kept offline`);
    },
  };
}
